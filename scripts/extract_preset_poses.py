"""Extract the SOMA-30 anchor poses used by the web editor's path presets.

The parametric path presets (demo/editor/presets.js) pin real Kimodo poses:
- a standing idle pose (three consecutive frames) for presets that start or end
  standing (Start, Stop, Turn in place, ...), placed like tools/mm_factory does;
- a walking pose for the frame-0 Hips end-effector pin that prevents the
  "floating start" on turning paths (docs/motion-stage-research/09, diagnosis).

Both come from the neutral smoke run of the motion-matching factory prototype
(kimodo-soma-rp-v1.1, seed 1): the idle pose is the calmest frame of the
standing clip (the factory's idle anchor), the walking pose is frame 0 of the
straight 1.2 m/s forward walk (the research's verified Hips-pin source: frame 0
of a straight-line clip).

Each pose is stored relative to its smooth root and turned so its hip line faces
exactly +Z (heading 0); a triplet shares the correction of its middle frame so
the frame-to-frame motion is kept.

usage: python -I scripts/extract_preset_poses.py [--work factory-output/_smoke_neutral/_work]
       [--out demo/editor/preset_poses.js]
"""
import argparse
import json
import math
import os

import numpy as np

J = 30
LLEG, RLEG = 22, 26
# SOMA-30 hip offsets from the pelvis (src/skeleton.hpp).
OFFSET_LLEG = np.array([.10043214, -.0843452671, .0259565473])
OFFSET_RLEG = np.array([-.10047278, -.0829525995, .0262031695])


def load(d):
    rd = lambda name, cols: np.fromfile(os.path.join(d, name), dtype="<f4").astype(np.float64).reshape(-1, *cols)
    return {"root": rd("root_positions.f32", (3,)), "rot": rd("local_rotations_xyzw.f32", (J, 4)),
            "smooth": rd("smooth_root.f32", (3,))}


def qmul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return np.array([aw * bx + ax * bw + ay * bz - az * by, aw * by - ax * bz + ay * bw + az * bx,
                     aw * bz + ax * by - ay * bx + az * bw, aw * bw - ax * bx - ay * by - az * bz])


def qrot(q, v):
    x, y, z, w = q
    u = np.array([x, y, z])
    return v + 2 * np.cross(u, np.cross(u, v) + w * v)


def yaw_quat(theta):
    return np.array([0.0, math.sin(theta / 2), 0.0, math.cos(theta / 2)])


def heading(hips_q):
    """Engine heading (src/constraints.cpp): atan2(d.z, -d.x), d = RightLeg - LeftLeg."""
    d = qrot(hips_q, OFFSET_RLEG) - qrot(hips_q, OFFSET_LLEG)
    return math.atan2(d[2], -d[0])


def axis_angle(q):
    q = np.asarray(q, np.float64)
    q = q / np.linalg.norm(q)
    if q[3] < 0:
        q = -q
    s = np.linalg.norm(q[:3])
    if s < 1e-12:
        return [0.0, 0.0, 0.0]
    return list(q[:3] / s * (2 * math.atan2(s, q[3])))


def rot_y(xz, theta):
    c, s = math.cos(theta), math.sin(theta)
    return np.array([c * xz[0] + s * xz[1], -s * xz[0] + c * xz[1]])


def pose(m, f, correction):
    q = m["rot"][f].copy()
    q[0] = qmul(yaw_quat(correction), q[0])
    off = rot_y(m["root"][f][[0, 2]] - m["smooth"][f][[0, 2]], correction)
    r6 = lambda v: round(float(v), 6)
    return {"rot": [[r6(c) for c in axis_angle(q[j])] for j in range(J)],
            "pelvis": [r6(off[0]), r6(m["root"][f][1]), r6(off[1])]}


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", default=os.path.join(here, "factory-output", "_smoke_neutral", "_work"))
    ap.add_argument("--idle-frame", type=int, default=15, help="the factory's idle anchor (manifest idle_pose_source_frame)")
    ap.add_argument("--out", default=os.path.join(here, "demo", "editor", "preset_poses.js"))
    args = ap.parse_args()

    idle = load(os.path.join(args.work, "idle_pass1", "seed1"))
    walk = load(os.path.join(args.work, "loop_Fwd_pass1", "seed1"))
    f = args.idle_frame
    h_idle = heading(idle["rot"][f][0])
    h_walk = heading(walk["rot"][0][0])
    data = {
        "idle": {"prev": pose(idle, f - 1, -h_idle), "pose": pose(idle, f, -h_idle), "next": pose(idle, f + 1, -h_idle)},
        "walk": pose(walk, 0, -h_walk),
    }
    for name, p in (("idle", data["idle"]["pose"]), ("walk", data["walk"])):
        print(f"{name}: pelvis offset/height {p['pelvis']}")
    print(f"heading corrections: idle {math.degrees(-h_idle):+.2f} deg, walk {math.degrees(-h_walk):+.2f} deg")

    body = json.dumps(data, separators=(",", ":"))
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(
            "// SOMA-30 anchor poses for the parametric path presets (presets.js).\n"
            "// GENERATED by scripts/extract_preset_poses.py; do not edit by hand.\n"
            "//\n"
            "// Source: the neutral smoke run of tools/mm_factory (kimodo-soma-rp-v1.1, seed 1,\n"
            "// 2026-10-09): `idle` is frames 14-16 of the standing clip (frame 15 is the\n"
            "// factory's calmest-frame idle anchor), `walk` is frame 0 of the straight\n"
            "// 1.2 m/s forward walk (the research's Hips-pin source, frame 0 of a line clip).\n"
            "//\n"
            "// Pose = {rot: [30][3] local axis-angle (constraints.json form, joint 0 = Hips,\n"
            "// global), pelvis: [dx, y, dz]}: (dx, dz) is the pelvis offset from the smooth\n"
            "// root and y the pelvis height in metres. Every pose is turned so its hip line\n"
            "// faces exactly +Z (engine heading 0); the idle triplet shares one correction.\n"
            f"export const PRESET_POSES = Object.freeze({{ soma30: {body} }});\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
